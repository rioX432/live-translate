import {
  ANIMATION_PREFERENCES,
  BUILTIN_CHARACTER_IDS,
  CHARACTER_STATES,
  ERROR_REACTIONS,
  IMAGE_EXTENSIONS,
  LEARNED_REACTIONS,
  MEETING_PRESENCES,
  PERSONA_STYLES,
  SPEECH_LENGTHS,
  SPEECH_POLITENESS,
  UNCERTAIN_REACTIONS,
  type BuiltinCharacterId,
  type CharacterAppearance,
  type CharacterDisplaySettings,
  type CharacterPosition,
  type CharacterProfile,
  type CharacterSettings,
  type CharacterState
} from './types'

export const CHARACTER_SCHEMA_VERSION = 1

export const CHARACTER_SIZE_MIN = 48
export const CHARACTER_SIZE_MAX = 256
export const CHARACTER_OPACITY_MIN = 0.2
export const CHARACTER_OPACITY_MAX = 1
export const CHARACTER_NAME_MAX = 40
export const CHARACTER_FIRST_PERSON_MAX = 20
export const CHARACTER_NOTE_MAX = 500
/** Profiles are user-managed; the cap keeps the settings file small */
export const CHARACTER_PROFILES_MAX = 20

/** Imported profile ids are generated by main; the pattern keeps them safe as directory names */
export const CUSTOM_PROFILE_ID_PATTERN = /^custom-[a-f0-9]{8,32}$/
const ASSET_FILE_PATTERN = new RegExp(
  `^(${CHARACTER_STATES.join('|')})-[a-f0-9]{6,16}\\.(${IMAGE_EXTENSIONS.join('|')})$`
)

export function isSafeAssetFileName(name: unknown): name is string {
  return typeof name === 'string' && ASSET_FILE_PATTERN.test(name)
}

const BUILTIN_NAMES: Record<BuiltinCharacterId, string> = {
  mochi: 'Mochi',
  pico: 'Pico'
}

export function builtinProfileId(id: BuiltinCharacterId): string {
  return `builtin-${id}`
}

export function defaultProfile(id: string, name: string, appearance: CharacterAppearance): CharacterProfile {
  return {
    id,
    name,
    appearance,
    persona: { style: 'friendly', firstPerson: '', note: '' },
    voice: { length: 'short', politeness: 'polite', tts: null },
    reactions: { expressions: true, learned: 'hop', uncertain: 'tilt', error: 'shake' }
  }
}

function builtinProfiles(): CharacterProfile[] {
  return BUILTIN_CHARACTER_IDS.map((id) =>
    defaultProfile(builtinProfileId(id), BUILTIN_NAMES[id], { kind: 'builtin', builtinId: id })
  )
}

export const DEFAULT_CHARACTER_DISPLAY: CharacterDisplaySettings = {
  visible: true,
  sizePx: 96,
  opacity: 1,
  animation: 'follow-os',
  inMeeting: 'compact',
  positionByDisplay: {}
}

export function defaultCharacterSettings(): CharacterSettings {
  return {
    schemaVersion: CHARACTER_SCHEMA_VERSION,
    activeCharacterId: builtinProfileId('mochi'),
    characters: builtinProfiles(),
    display: { ...DEFAULT_CHARACTER_DISPLAY, positionByDisplay: {} }
  }
}

// --- normalization helpers ---

function isRecord(v: unknown): v is Record<string, unknown> {
  return typeof v === 'object' && v !== null && !Array.isArray(v)
}

function oneOf<T extends string>(allowed: readonly T[], v: unknown, fallback: T): T {
  return typeof v === 'string' && (allowed as readonly string[]).includes(v) ? (v as T) : fallback
}

function text(v: unknown, max: number, fallback: string): string {
  if (typeof v !== 'string') return fallback
  // Strip control characters; these strings end up in UI and future prompts
  // eslint-disable-next-line no-control-regex
  return v.replace(/[\u0000-\u0008\u000b-\u001f\u007f]/g, '').slice(0, max)
}

function clampNumber(v: unknown, min: number, max: number, fallback: number): number {
  if (typeof v !== 'number' || !Number.isFinite(v)) return fallback
  return Math.min(max, Math.max(min, v))
}

function normalizePosition(v: unknown): CharacterPosition | null {
  if (!isRecord(v)) return null
  const { x, y } = v
  if (typeof x !== 'number' || typeof y !== 'number' || !Number.isFinite(x) || !Number.isFinite(y)) return null
  return { x: Math.round(x), y: Math.round(y) }
}

function normalizeDisplay(v: unknown): CharacterDisplaySettings {
  const d = DEFAULT_CHARACTER_DISPLAY
  if (!isRecord(v)) return { ...d, positionByDisplay: {} }
  const positions: Record<string, CharacterPosition> = {}
  if (isRecord(v.positionByDisplay)) {
    for (const [key, raw] of Object.entries(v.positionByDisplay)) {
      const pos = normalizePosition(raw)
      if (/^\d{1,20}$/.test(key) && pos) positions[key] = pos
    }
  }
  return {
    visible: typeof v.visible === 'boolean' ? v.visible : d.visible,
    sizePx: Math.round(clampNumber(v.sizePx, CHARACTER_SIZE_MIN, CHARACTER_SIZE_MAX, d.sizePx)),
    opacity: clampNumber(v.opacity, CHARACTER_OPACITY_MIN, CHARACTER_OPACITY_MAX, d.opacity),
    animation: oneOf(ANIMATION_PREFERENCES, v.animation, d.animation),
    inMeeting: oneOf(MEETING_PRESENCES, v.inMeeting, d.inMeeting),
    positionByDisplay: positions
  }
}

function normalizeAppearance(v: unknown): CharacterAppearance | null {
  if (!isRecord(v)) return null
  if (v.kind === 'builtin') {
    const id = oneOf(BUILTIN_CHARACTER_IDS, v.builtinId, 'mochi')
    return { kind: 'builtin', builtinId: id }
  }
  if (v.kind === 'image') {
    const assets: Partial<Record<CharacterState, string>> = {}
    if (isRecord(v.assets)) {
      for (const state of CHARACTER_STATES) {
        const file = v.assets[state]
        // Asset names must start with their own state so one file cannot be
        // claimed under another key and later deleted twice
        if (isSafeAssetFileName(file) && file.startsWith(`${state}-`)) assets[state] = file
      }
    }
    if (!assets.idle) return null
    return { kind: 'image', assets, pixelArt: v.pixelArt === true }
  }
  return null
}

function normalizeProfile(v: unknown, fallbackName: string): CharacterProfile | null {
  if (!isRecord(v) || typeof v.id !== 'string') return null
  const appearance = normalizeAppearance(v.appearance)
  if (!appearance) return null
  const builtinId = appearance.kind === 'builtin' ? builtinProfileId(appearance.builtinId) : null
  // Built-in profiles keep their fixed id; imported ones must match the generated pattern
  if (builtinId ? v.id !== builtinId : !CUSTOM_PROFILE_ID_PATTERN.test(v.id)) return null

  const base = defaultProfile(v.id, fallbackName, appearance)
  const persona = isRecord(v.persona) ? v.persona : {}
  const voice = isRecord(v.voice) ? v.voice : {}
  const reactions = isRecord(v.reactions) ? v.reactions : {}
  const name = text(v.name, CHARACTER_NAME_MAX, '').trim()
  return {
    id: v.id,
    name: name || fallbackName,
    appearance,
    persona: {
      style: oneOf(PERSONA_STYLES, persona.style, base.persona.style),
      firstPerson: text(persona.firstPerson, CHARACTER_FIRST_PERSON_MAX, base.persona.firstPerson),
      note: text(persona.note, CHARACTER_NOTE_MAX, base.persona.note)
    },
    voice: {
      length: oneOf(SPEECH_LENGTHS, voice.length, base.voice.length),
      politeness: oneOf(SPEECH_POLITENESS, voice.politeness, base.voice.politeness),
      tts: null
    },
    reactions: {
      expressions: typeof reactions.expressions === 'boolean' ? reactions.expressions : base.reactions.expressions,
      learned: oneOf(LEARNED_REACTIONS, reactions.learned, base.reactions.learned),
      uncertain: oneOf(UNCERTAIN_REACTIONS, reactions.uncertain, base.reactions.uncertain),
      error: oneOf(ERROR_REACTIONS, reactions.error, base.reactions.error)
    }
  }
}

/**
 * Turn whatever is on disk (or sent over IPC) into valid settings.
 * Unknown or broken fields fall back to defaults, built-in characters are
 * always present, and the active id always points at an existing profile.
 * Data from a newer schema version is normalized field by field rather than
 * discarded, so a downgrade keeps the user's characters where it can.
 */
export function migrateCharacterSettings(raw: unknown): CharacterSettings {
  const defaults = defaultCharacterSettings()
  if (!isRecord(raw)) return defaults

  const seen = new Set<string>()
  const characters: CharacterProfile[] = []
  const rawList = Array.isArray(raw.characters) ? raw.characters : []
  for (const item of rawList) {
    if (characters.length >= CHARACTER_PROFILES_MAX) break
    const fallbackName = isRecord(item) && isRecord(item.appearance) && item.appearance.kind === 'builtin'
      ? BUILTIN_NAMES[oneOf(BUILTIN_CHARACTER_IDS, item.appearance.builtinId, 'mochi')]
      : 'My character'
    const profile = normalizeProfile(item, fallbackName)
    if (profile && !seen.has(profile.id)) {
      seen.add(profile.id)
      characters.push(profile)
    }
  }
  // Built-ins cannot be deleted: they always come first in their fixed order,
  // keeping any user edits, followed by imported characters in saved order
  const builtins = defaults.characters.map((d) => characters.find((p) => p.id === d.id) ?? d)
  const merged = [...builtins, ...characters.filter((p) => p.appearance.kind !== 'builtin')]

  const activeId = typeof raw.activeCharacterId === 'string' && merged.some((p) => p.id === raw.activeCharacterId)
    ? raw.activeCharacterId
    : defaults.activeCharacterId

  return {
    schemaVersion: CHARACTER_SCHEMA_VERSION,
    activeCharacterId: activeId,
    characters: merged,
    display: normalizeDisplay(raw.display)
  }
}

export function activeProfile(settings: CharacterSettings): CharacterProfile {
  return settings.characters.find((p) => p.id === settings.activeCharacterId) ?? settings.characters[0]
}
